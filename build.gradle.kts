// The README's screenshots are generated by the Robolectric generators in :tools:screenshots and
// versioned under docs/screenshots/, so a reader sees the app without running anything. The
// notification shot is the one exception: the system shade is not a composable, so it stays a
// manual capture. See docs/screenshots.md.
private val generatedScreenshotsPath = "outputs/screenshots"
private val readmeScreenshotWidth = 520
private val manualScreenshots = setOf("notification.png")

private val clearGeneratedScreenshots = tasks.register<Delete>("clearGeneratedScreenshots") {
    delete(layout.buildDirectory.dir(generatedScreenshotsPath))
}

project(":tools:screenshots").tasks.matching { task -> task.name.startsWith("test") }.configureEach {
    dependsOn(clearGeneratedScreenshots)
}

tasks.register("updateReadmeScreenshots") {
    group = "screenshots"
    description = "Regenerates the screenshots the README shows and writes them to docs/screenshots/."
    dependsOn(":tools:screenshots:testDebugUnitTest")
    val generatedDir = layout.buildDirectory.dir("$generatedScreenshotsPath/en-US/images/readme")
    val screenshotsDir = layout.projectDirectory.dir("docs/screenshots")
    val targetWidth = readmeScreenshotWidth
    val manual = manualScreenshots
    doLast {
        // Drawn down in halving steps before the last one: a single draw from 1242px samples too
        // few of the pixels it skips and leaves hairlines and small text ragged.
        fun BufferedImage.renderAt(width: Int): BufferedImage {
            val height = (this.height.toLong() * width / this.width).toInt()
            val scaled = BufferedImage(width, height, BufferedImage.TYPE_INT_RGB)
            val graphics = scaled.createGraphics()
            graphics.setRenderingHint(RenderingHints.KEY_INTERPOLATION, RenderingHints.VALUE_INTERPOLATION_BILINEAR)
            graphics.drawImage(this, 0, 0, width, height, null)
            graphics.dispose()
            return scaled
        }

        fun BufferedImage.renderScaledTo(width: Int): BufferedImage {
            var current = this
            while (current.width > width * 2) {
                current = current.renderAt(current.width / 2)
            }
            return if (current.width == width) current else current.renderAt(width)
        }

        val generated = generatedDir
            .get()
            .asFile
            .listFiles { file -> file.extension == "png" }
            .orEmpty()
            .sortedBy { png -> png.name }
        // Collected before anything is deleted: docs/screenshots/ is versioned, and a filtered run
        // that produced nothing would otherwise empty it and take the README's images with it.
        check(generated.isNotEmpty()) {
            "No screenshots were generated under ${generatedDir.get().asFile}."
        }
        // Wiped so a shot that was renamed or dropped cannot stay in the folder — and in the
        // README — forever.
        screenshotsDir
            .asFile
            .listFiles { file -> file.extension == "png" && file.name !in manual }
            .orEmpty()
            .forEach { png -> png.delete() }
        generated.forEach { png ->
            val scaled = ImageIO.read(png).renderScaledTo(targetWidth)
            ImageIO.write(scaled, "png", screenshotsDir.asFile.resolve(png.name))
        }
        logger.lifecycle("updateReadmeScreenshots: wrote ${generated.size} screenshot(s) into docs/screenshots/")
    }
}
